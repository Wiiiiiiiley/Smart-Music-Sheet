import assert from 'node:assert/strict'
const delay = ms => new Promise(resolve => setTimeout(resolve, ms))

export async function collaborationFeatures({ json, connect, next, emit, observe, ensemble, violin, cello, fileUrl }) {
  const conductor = await connect(ensemble.members[0])
  const violinSocket = await connect(violin)
  const celloSocket = await connect(cello)
  const conductorMarks = observe(conductor, 'mark-added'), celloMarks = observe(celloSocket, 'mark-added')
  const conductorDeletes = observe(conductor, 'mark-deleted'), celloDeletes = observe(celloSocket, 'mark-deleted')
  const celloCues = observe(celloSocket, 'cue-received'), violinMistakes = observe(violinSocket, 'mistake-received')
  const score = await json('/api/scores', 'POST', { title: '协作功能回归', fileUrl, fileType: 'musicxml', ensembleId: ensemble.id }, 201)
  const sendWait = async (socket, event, action, predicate = () => true) => {
    let waiting = next(socket, event)
    action()
    for (;;) {
      const value = await waiting
      if (predicate(value)) return value
      waiting = next(socket, event)
    }
  }
  await sendWait(violinSocket, 'score-selected', () => emit(conductor, 'score-select', { scoreId: score.id }), data => data.scoreId === score.id)
  const individual = await sendWait(conductor, 'mark-added', () => emit(conductor, 'add-mark', { scoreId: score.id, type: 'TEXT', data: '仅此乐手', x: 0.1, y: 0.2, page: 1, targetMemberId: violin.id }))
  assert.equal(individual.targetMemberId, violin.id)
  assert.equal(individual.private, false)
  const privateMark = await sendWait(violinSocket, 'mark-added', () => emit(violinSocket, 'add-mark', { scoreId: score.id, type: 'TEXT', data: '个人指法', x: 0.4, y: 0.2, page: 1, private: false, targetSection: 'cello' }), data => data.private)
  assert.equal(privateMark.creatorId, violin.id)
  assert.equal(privateMark.private, true)
  assert.ok(!(await json(`/api/scores/${score.id}?memberId=${ensemble.conductorId}`)).marks.some(mark => mark.id === privateMark.id))
  assert.equal((await json(`/api/scores/${score.id}/marks?memberId=${violin.id}`)).length, 2)
  assert.equal((await json(`/api/scores/${score.id}/marks?memberId=${cello.id}`)).length, 0)
  assert.equal((await json(`/api/scores/${score.id}/marks`)).length, 0)
  await json(`/api/scores/${score.id}?memberId=missing-member`, 'GET', undefined, 403)
  await sendWait(celloSocket, 'error', () => emit(celloSocket, 'delete-mark', privateMark.id))
  await sendWait(violinSocket, 'mark-deleted', () => emit(conductor, 'delete-mark', privateMark.id), data => data === privateMark.id)
  assert.ok(!conductorDeletes.includes(privateMark.id), 'private deletion must not reveal private note to conductor')
  await sendWait(conductor, 'mark-deleted', () => emit(conductor, 'delete-mark', individual.id), data => data === individual.id)
  await json(`/api/scores/${score.id}/measures`, 'PUT', { memberId: cello.id, measures: [{ number: 1 }] }, 403)
  let measures = await json(`/api/scores/${score.id}/measures`, 'PUT', { memberId: ensemble.conductorId, measures: [{ number: 2, startTime: 2, endTime: 4 }, { number: 1, startTime: 0, endTime: 2 }] })
  assert.deepEqual(measures.map(measure => measure.number), [1, 2])
  const originalId = measures[0].id
  measures = await json(`/api/scores/${score.id}/measures`, 'PUT', { memberId: ensemble.conductorId, measures: [{ number: 1 }, { number: 3, startTime: 4 }] })
  assert.equal(measures[0].id, originalId)
  assert.equal(measures[0].startTime, 0)
  assert.deepEqual(measures.map(measure => measure.number), [1, 3])
  await json(`/api/scores/${score.id}/measures`, 'PUT', { memberId: ensemble.conductorId, measures: [{ number: 1, startTime: 10, endTime: 2 }] }, 400)
  const tracks = [{ id: 'violin-track', label: '第一小提琴', section: 'violin1', audioUrl: '/uploads/audio/violin.ogg', volume: 0.6 }]
  await json(`/api/scores/${score.id}/tracks`, 'PUT', { memberId: cello.id, tracks }, 403)
  const trackUpdated = next(violinSocket, 'score-tracks-updated')
  assert.deepEqual(await json(`/api/scores/${score.id}/tracks`, 'PUT', { memberId: ensemble.conductorId, tracks }), tracks)
  assert.deepEqual((await trackUpdated).tracks, tracks)
  assert.deepEqual(await json(`/api/scores/${score.id}/tracks?memberId=${violin.id}`), tracks)
  const regions = [{ number: 1, page: 1, x: 0.1, y: 0.2, width: 0.4, height: 0.2 }]
  assert.deepEqual(await json(`/api/scores/${score.id}/layout`, 'PUT', { memberId: ensemble.conductorId, regions }), regions)
  const roundTrip = await json(`/api/scores/${score.id}?memberId=${violin.id}`)
  assert.deepEqual(roundTrip.audioTracks, tracks)
  assert.deepEqual(roundTrip.measureRegions, regions)
  await json(`/api/scores/${score.id}/layout`, 'PUT', { memberId: ensemble.conductorId, regions: [{ ...regions[0], x: -1 }] }, 400)
  const rehearsal = await json('/api/rehearsals/start', 'POST', { ensembleId: ensemble.id, scoreId: score.id }, 201)
  await sendWait(conductor, 'rehearsal-started', () => emit(conductor, 'rehearsal-start', { rehearsalId: rehearsal.id, scoreId: score.id }), data => data.rehearsalId === rehearsal.id)
  const cue = await sendWait(conductor, 'cue-received', () => emit(conductor, 'send-cue', { type: 'COUNT_IN', bpm: 100, scoreId: score.id, measureNumber: 3, targetMemberId: violin.id }))
  assert.ok(cue.id)
  assert.ok(cue.timestamp)
  const stopped = await sendWait(violinSocket, 'audio-control', () => emit(conductor, 'audio-control', { action: 'STOP_CUE', targetMemberId: violin.id }))
  assert.equal(stopped.action, 'STOP_CUE', 'cue controls work before anyone opens the live microphone room')
  await sendWait(violinSocket, 'error', () => emit(violinSocket, 'send-mistake', { scoreId: score.id, measure: 3, kind: 'RHYTHM', note: '抢拍' }))
  const mistake = await sendWait(conductor, 'mistake-received', () => emit(conductor, 'send-mistake', { scoreId: score.id, measure: 3, kind: 'RHYTHM', note: '抢拍', targetMemberId: violin.id }))
  assert.equal(mistake.reporterId, ensemble.conductorId)
  const history = await json(`/api/ensembles/${ensemble.id}/cues?memberId=${violin.id}`)
  assert.ok(history.some(item => item.id === cue.id))
  assert.ok(!(await json(`/api/ensembles/${ensemble.id}/cues?memberId=${cello.id}`)).some(item => item.id === cue.id))
  const conductorLog = await json(`/api/rehearsals/${rehearsal.id}?memberId=${ensemble.conductorId}`)
  assert.ok(conductorLog.events.some(event => event.type === 'CUE_SENT' && JSON.parse(event.data).id === cue.id))
  assert.ok(conductorLog.events.some(event => event.type === 'MISTAKE_REPORTED' && JSON.parse(event.data).id === mistake.id))
  const celloLog = await json(`/api/rehearsals/${rehearsal.id}?memberId=${cello.id}`)
  assert.ok(!celloLog.events.some(event => event.type === 'MISTAKE_REPORTED' || event.type === 'CUE_SENT'))
  assert.ok((await json(`/api/rehearsals/${rehearsal.id}?memberId=${violin.id}`)).events.some(event => event.type === 'MISTAKE_REPORTED'))
  const position = { scoreId: score.id, measure: 3, beat: 1, bpm: 100, beatsPerMeasure: 4, running: true, startedAt: Date.now(), entryMeasures: { violin1: 8, cello: 12 } }
  await sendWait(conductor, 'position-updated', () => emit(conductor, 'current-position', position), data => data.measure === 3)
  const late = await connect(cello)
  const restored = await sendWait(late, 'position-updated', () => emit(late, 'join-ensemble', { ensembleId: ensemble.id, memberId: cello.id }))
  assert.deepEqual(restored.entryMeasures, position.entryMeasures)
  assert.equal(restored.running, true)
  await json(`/api/rehearsals/${rehearsal.id}/recording`, 'PUT', { memberId: violin.id, recordingUrl: '/uploads/audio/private.webm' }, 403)
  assert.equal((await json(`/api/rehearsals/${rehearsal.id}/recording`, 'PUT', { memberId: ensemble.conductorId, recordingUrl: '/uploads/audio/live.webm' })).recordingUrl, '/uploads/audio/live.webm')
  await json(`/api/rehearsals/${rehearsal.id}/end`, 'POST', {})
  assert.equal((await json(`/api/rehearsals/${rehearsal.id}/recording`, 'PUT', { memberId: ensemble.conductorId, recordingUrl: '/uploads/audio/final.mp4' })).recordingUrl, '/uploads/audio/final.mp4')
  assert.equal((await json(`/api/rehearsals/${rehearsal.id}?memberId=${ensemble.conductorId}`)).recordingUrl, '/uploads/audio/final.mp4')
  await delay(50)
  assert.ok(!conductorMarks.some(mark => mark.id === privateMark.id))
  assert.equal(celloMarks.length, 0)
  assert.equal(celloDeletes.length, 0)
  assert.equal(celloCues.length, 0)
  assert.equal(violinMistakes.length, 1)
  console.log('Collaboration feature contract passed: private/personal marks, filtered cue and mistake logs, measure mapping, tracks/layout roundtrip, late-join position, recording before/after end.')
}
